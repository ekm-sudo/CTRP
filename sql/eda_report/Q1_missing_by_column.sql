-- CTRP EDA report Q1: Missing data: blank share of every column, zero-or-less share of every number
-- Run as ONE statement in Hue, download as CSV, save as data/eda_report/Q1.csv
SELECT COUNT(*) AS item_rows,
       AVG(CASE WHEN instance_id IS NULL THEN 1D ELSE 0D END) AS blank_instance_id,
       AVG(CASE WHEN entry_num IS NULL THEN 1D ELSE 0D END) AS blank_entry_num,
       AVG(CASE WHEN dec_ref_yer IS NULL THEN 1D ELSE 0D END) AS blank_dec_ref_yer,
       AVG(CASE WHEN clearance_station_cd IS NULL THEN 1D ELSE 0D END) AS blank_clearance_station_cd,
       AVG(CASE WHEN taxpayer_tin IS NULL THEN 1D ELSE 0D END) AS blank_taxpayer_tin,
       AVG(CASE WHEN taxpayer_nm IS NULL THEN 1D ELSE 0D END) AS blank_taxpayer_nm,
       AVG(CASE WHEN consignee_tin IS NULL THEN 1D ELSE 0D END) AS blank_consignee_tin,
       AVG(CASE WHEN hsc_cd IS NULL THEN 1D ELSE 0D END) AS blank_hsc_cd,
       AVG(CASE WHEN gds_org_cty IS NULL THEN 1D ELSE 0D END) AS blank_gds_org_cty,
       AVG(CASE WHEN cpc_cd IS NULL THEN 1D ELSE 0D END) AS blank_cpc_cd,
       AVG(CASE WHEN extended_proc_cd IS NULL THEN 1D ELSE 0D END) AS blank_extended_proc_cd,
       AVG(CASE WHEN decl_status IS NULL THEN 1D ELSE 0D END) AS blank_decl_status,
       AVG(CASE WHEN pay_status IS NULL THEN 1D ELSE 0D END) AS blank_pay_status,
       AVG(CASE WHEN key_itm_nbr IS NULL THEN 1D ELSE 0D END) AS blank_key_itm_nbr,
       AVG(CASE WHEN top_up_flg IS NULL THEN 1D ELSE 0D END) AS blank_top_up_flg,
       AVG(CASE WHEN amendment_flg IS NULL THEN 1D ELSE 0D END) AS blank_amendment_flg,
       AVG(CASE WHEN preferential_treatment_flag IS NULL THEN 1D ELSE 0D END) AS blank_preferential_treatment_flag,
       AVG(CASE WHEN assessment_dt_wid IS NULL THEN 1D ELSE 0D END) AS blank_assessment_dt_wid,
       AVG(CASE WHEN customs_value IS NULL THEN 1D ELSE 0D END) AS blank_customs_value,
       AVG(CASE WHEN net_weight IS NULL THEN 1D ELSE 0D END) AS blank_net_weight,
       AVG(CASE WHEN supplementary_qnty IS NULL THEN 1D ELSE 0D END) AS blank_supplementary_qnty,
       AVG(CASE WHEN tax_assessed IS NULL THEN 1D ELSE 0D END) AS blank_tax_assessed,
       AVG(CASE WHEN original_tax_amt IS NULL THEN 1D ELSE 0D END) AS blank_original_tax_amt,
       AVG(CASE WHEN final_amt IS NULL THEN 1D ELSE 0D END) AS blank_final_amt,
       AVG(CASE WHEN top_up_amt IS NULL THEN 1D ELSE 0D END) AS blank_top_up_amt,
       AVG(CASE WHEN is_red_flg IS NULL THEN 1D ELSE 0D END) AS blank_is_red_flg,
       AVG(CASE WHEN is_yellow_flg IS NULL THEN 1D ELSE 0D END) AS blank_is_yellow_flg,
       AVG(CASE WHEN customs_value <= 0 THEN 1D WHEN customs_value IS NULL THEN NULL ELSE 0D END) AS zero_or_less_customs_value,
       AVG(CASE WHEN net_weight <= 0 THEN 1D WHEN net_weight IS NULL THEN NULL ELSE 0D END) AS zero_or_less_net_weight,
       AVG(CASE WHEN supplementary_qnty <= 0 THEN 1D WHEN supplementary_qnty IS NULL THEN NULL ELSE 0D END) AS zero_or_less_supplementary_qnty,
       AVG(CASE WHEN tax_assessed <= 0 THEN 1D WHEN tax_assessed IS NULL THEN NULL ELSE 0D END) AS zero_or_less_tax_assessed,
       AVG(CASE WHEN original_tax_amt <= 0 THEN 1D WHEN original_tax_amt IS NULL THEN NULL ELSE 0D END) AS zero_or_less_original_tax_amt,
       AVG(CASE WHEN final_amt <= 0 THEN 1D WHEN final_amt IS NULL THEN NULL ELSE 0D END) AS zero_or_less_final_amt,
       AVG(CASE WHEN top_up_amt <= 0 THEN 1D WHEN top_up_amt IS NULL THEN NULL ELSE 0D END) AS zero_or_less_top_up_amt
FROM dm_modeled_ura_datascience.vw_cstm_AEO_model
WHERE assessment_dt_wid > '20240930' AND assessment_dt_wid <= '20260930' AND regime_cd IN ('IM4', 'IM7')
