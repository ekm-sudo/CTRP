def _paragraph(text, i):
    """One Zeppelin paragraph in the .zpln format (Zeppelin 0.10)."""
    pid = f'paragraph_ctrp_{i:02d}'
    lang = 'markdown' if text.startswith('%md') else 'python'
    return {'title': None, 'text': text, 'user': 'anonymous', 'dateUpdated': '2026-10-13 00:00:00.000',
            'progress': 0, 'config': {'editorSetting': {'language': lang, 'editOnDblClick': lang == 'markdown',
                                                        'completionSupport': lang != 'markdown'},
                                      'editorMode': f'ace/mode/{lang}', 'colWidth': 12.0, 'fontSize': 9.0,
                                      'editorHide': False, 'results': {}, 'enabled': True},
            'settings': {'params': {}, 'forms': {}}, 'apps': [], 'runtimeInfos': {},
            'progressUpdateIntervalMs': 500, 'jobName': pid, 'id': pid,
            'dateCreated': '2026-10-13 00:00:00.000', 'status': 'READY'}


def note_paragraphs():
    """The note's paragraphs in order (without NOTE_HELLO), settings and queries filled in."""
    settings = _fill_settings(NOTE_SETTINGS, repr(_snapshots()), repr(PREF_ORIGINS))
    defs = _fill_sql(NOTE_DEFS)
    return [NOTE_INTRO, settings, NOTE_RANGE, defs, NOTE_TEST, NOTE_ALL, NOTE_CHECK, NOTE_DOWNLOAD]


def write_note(path=OUT_NOTE):
    """Write CTRP_extracts.zpln: the intro, then the Spark and home-folder check, then the rest."""
    texts = note_paragraphs()
    texts = texts[:1] + [NOTE_HELLO] + texts[1:]
    note = {'paragraphs': [_paragraph(t, i) for i, t in enumerate(texts)],
            'name': 'CTRP extracts', 'id': 'CTRPEXTRACTS01', 'defaultInterpreterGroup': 'spark',
            'version': '0.10.1', 'noteParams': {}, 'noteForms': {}, 'angularObjects': {},
            'config': {'isZeppelinNotebookCronEnable': False}, 'info': {}}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(note, indent=2))
    print(f'written {path.relative_to(PROJECT_ROOT)} ({len(note["paragraphs"])} paragraphs)')
    return path


