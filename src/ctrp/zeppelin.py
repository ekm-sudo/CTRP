def _snapshots():
    """Every snapshot to pull, as (date, live?) pairs: the back-test dates, then the live date."""
    return [(s, False) for s in E.BACKTEST_SNAPSHOTS] + [(E.LIVE_SNAPSHOT, True)]


def _fill_settings(text, snapshots_text, pref_text):
    """Put the project's settings into a script or note paragraph (the __NAME__ placeholders)."""
    values = {'__SNAPSHOTS__': snapshots_text,
              '__HIST__': str(E.HISTORY_MONTHS),
              '__YEARS__': str(E.YEARS_MONTHS),
              '__OUT__': str(E.OUTCOME_MONTHS),
              '__PRIOR__': str(E.PRIOR_MONTHS),
              '__PREF__': pref_text}
    for key, value in values.items():
        text = text.replace(key, value)
    return text


def _fill_sql(text):
    """Put the three queries into a script or note paragraph."""
    items_sql, main_sql = split_main_template()
    return (text.replace('__ITEMS__', items_sql).replace('__MAIN__', main_sql)
                .replace('__TRACKB__', TRACKB_SQL.read_text()))


def write_script(path=OUT_SCRIPT):
    """Write the one-paragraph PySpark script (ctrp_extract.py) and check_data_range.py."""
    snapshots_text = json.dumps(_snapshots()).replace('false', 'False').replace('true', 'True')
    body = _fill_sql(_fill_settings(SCRIPT, snapshots_text, json.dumps(PREF_ORIGINS)))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body)
    (path.parent / 'check_data_range.py').write_text(CHECK)
    print(f'written {path.relative_to(PROJECT_ROOT)} and check_data_range.py')
    return path


