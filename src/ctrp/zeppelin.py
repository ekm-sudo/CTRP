"""
Zeppelin: pull every extract in one Spark session, instead of one Hue query at a time.

What: writes notebooks/zeppelin/ctrp_extract.py, a self-contained PySpark script to paste into a
      Zeppelin %pyspark paragraph. For each snapshot it
        1. builds the cleaned item table ONCE and keeps it in memory (ctrp_items),
        2. runs the main feature and outcome query on it (same SQL and columns as sql/<name>.sql),
        3. runs the Track B feature query on it (src/ctrp/sql/trackb_features.sql),
        4. writes both as CSV to OUT_DIR.
      The same work is also written as an importable note (CTRP_extracts.zpln) and as paste files.
Why:  Hue drops a query after about 30 minutes, and every Hue query rebuilt the item table from
      scratch, about a dozen times inside the full query. In one Spark session the table is built
      once per snapshot and reused, so the whole set of extracts runs in one go.

    python main.py zeppelin        -> notebooks/zeppelin/ctrp_extract.py, CTRP_extracts.zpln, paste/
"""
import json
from pathlib import Path

from ctrp import extract as E
from ctrp.utils import PROJECT_ROOT, TEMPLATE_SQL

TRACKB_SQL = Path(__file__).resolve().parent / 'sql' / 'trackb_features.sql'
OUT_SCRIPT = PROJECT_ROOT / 'notebooks' / 'zeppelin' / 'ctrp_extract.py'

# Preference partner states (EAC and COMESA), ISO two-letter codes. To be confirmed by the
# Risk Officers (meeting question 12) before the feature is scored.
PREF_ORIGINS = ['UG', 'KE', 'TZ', 'RW', 'BI', 'SS', 'CD', 'SO',                      # EAC
                'KM', 'DJ', 'EG', 'ER', 'SZ', 'ET', 'LY', 'MG', 'MW', 'MU', 'SC', 'SD',
                'TN', 'ZM', 'ZW']                                                   # COMESA (others)


def split_main_template():
    """The main template cut in two: the item-cleaning part, and the rest reading ctrp_items."""
    head, ctes, sel, frm = E._parse_template(E.apply_apc_483(TEMPLATE_SQL.read_text()))
    items_sql = 'WITH ' + ',\n\n'.join(ctes[n] for n in ['raw', 'items']) + '\n\nSELECT * FROM items\n'
    rest = {n: t for n, t in ctes.items() if n not in ('raw', 'items')}
    rest = {'p': rest.pop('p'), 'items': 'items AS (SELECT * FROM ctrp_items)', **rest}
    main_sql = ('WITH ' + ',\n\n'.join(rest.values()) +
                '\n\n-- ---------- final row per taxpayer ---\n' + sel + '\n' + frm)
    return items_sql, main_sql


SCRIPT = r'''%pyspark
# =====================================================================================
# CTRP extracts in Zeppelin: paste into ONE paragraph that starts with the line %pyspark
# GENERATED by: python main.py zeppelin. Edit the settings below, not the SQL.
# =====================================================================================
import calendar, datetime, time

# ---------- settings -------------------------------------------------------------------
OUT_DIR = '/user/CHANGE_ME/ctrp'        # a folder you can write to and download from (Hue file browser)
SNAPSHOTS = __SNAPSHOTS__               # (date, live?) pairs; delete any you already have
HISTORY_MONTHS = __HIST__               # months of history before each snapshot
YEARS_MONTHS = __YEARS__                # the y1/y2/y3 yearly counts reach back this far
OUTCOME_MONTHS = __OUT__                # months of outcomes after a back-test snapshot
PRIOR_MONTHS = __PRIOR__                # look-back that decides "new trader" in the main extract
PREF_ORIGINS = __PREF__                 # preference partner states (to be confirmed)
RUN_TRACK_B = True                      # also write the Track B behaviour features

ITEMS_SQL = """__ITEMS__"""
MAIN_SQL = """__MAIN__"""
TRACKB_SQL = """__TRACKB__"""


# ---------- dates -----------------------------------------------------------------------
def month_end(d, months):
    """The last day of the month `months` away from date d (negative = earlier)."""
    y, m = divmod(d.year * 12 + d.month - 1 + months, 12)
    return datetime.date(y, m + 1, calendar.monthrange(y, m + 1)[1])


def ymd(d):
    return d.strftime('%Y%m%d')


def fill(sql, snap, live):
    s = datetime.date.fromisoformat(snap)
    hist_start = month_end(s, -HISTORY_MONTHS)
    out_end = s if live else month_end(s, OUTCOME_MONTHS)
    values = {'@@SNAP_DATE@@': snap, '@@SNAP@@': ymd(s), '@@HIST_START@@': ymd(hist_start),
              '@@HIST3_START@@': ymd(month_end(s, -YEARS_MONTHS)), '@@OUT_END@@': ymd(out_end), '@@PRIOR_START@@': ymd(month_end(hist_start, -PRIOR_MONTHS)),
              '@@NEW_SINCE@@': ymd(month_end(s, -12)),
              '@@PREF_ORIGINS@@': ', '.join("'%s'" % c for c in PREF_ORIGINS)}
    for k, v in values.items():
        sql = sql.replace(k, v)
    return sql


def save(df, name):
    """One CSV per extract: OUT_DIR/<name>/part-....csv (rename it to <name>.csv after download)."""
    df.coalesce(1).write.mode('overwrite').option('header', True).csv(OUT_DIR + '/' + name)


# ---------- run -------------------------------------------------------------------------
for snap, live in SNAPSHOTS:
    name = ('live_' if live else 'bt_') + snap
    t0 = time.time()
    items = spark.sql(fill(ITEMS_SQL, snap, live))
    items.createOrReplaceTempView('ctrp_items')
    spark.catalog.cacheTable('ctrp_items')
    n_items = spark.table('ctrp_items').count()            # builds the cache once
    main = spark.sql(fill(MAIN_SQL, snap, live))
    save(main, name)
    n_tp = spark.read.option('header', True).csv(OUT_DIR + '/' + name).count()
    msg = '%s: %s items, %s taxpayers' % (name, format(n_items, ','), format(n_tp, ','))
    if RUN_TRACK_B:
        save(spark.sql(fill(TRACKB_SQL, snap, live)), 'trackb_' + name)
        msg += ', Track B written'
    spark.catalog.uncacheTable('ctrp_items')
    print(msg + ' in %.0f min' % ((time.time() - t0) / 60))
print('Done. Download each folder from ' + OUT_DIR + ' and save the CSV inside as data/<name>.csv '
      '(Track B: data/trackb/trackb_<name>.csv).')
'''

